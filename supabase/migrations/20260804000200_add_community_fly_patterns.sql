create or replace function public.community_fly_pattern_id_from_storage_name(object_name text)
returns uuid language plpgsql immutable security definer set search_path = '' as $$
declare value text;
begin
  value := (storage.foldername(object_name))[2];
  if value is null or value !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then
    return null;
  end if;
  return value::uuid;
end;
$$;
