-- HoodFlyLog moderated community fly-pattern library
-- REVIEW ONLY: this migration has not been executed.
--
-- Assumptions verified from the repository:
--   * public.profiles.id matches auth.users.id.
--   * public.is_moderator(uuid) already exists and recognizes moderators plus the
--     protected owner account. This migration deliberately creates no role-writing API.
--   * public.is_banned(uuid) already exists.
--   * The current private "My Flies" inventory lives in localStorage. Nothing in
--     this migration reads, changes, or replaces that data.
--   * Community images are uploaded only after a draft row exists, under:
--       <owner uuid>/<pattern uuid>/cover.<ext>
--       <owner uuid>/<pattern uuid>/steps/<step uuid>.<ext>

create extension if not exists pgcrypto;

-- Parent record and moderation lifecycle.
create table if not exists public.community_fly_patterns (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 160),
  category text not null default 'Other' check (length(btrim(category)) between 1 and 80),
  summary text,
  best_for text,
  fishing_notes text,
  video_url text,
  cover_image_path text,
  status text not null default 'draft'
    check (status in ('draft', 'pending', 'published', 'rejected')),
  rejection_reason text,
  submitted_at timestamptz,
  published_at timestamptz,
  moderated_at timestamptz,
  moderated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint community_fly_patterns_video_provider check (
    video_url is null or video_url ~* '^https://(((www|m)\.)?youtube\.com/|youtu\.be/|(www\.)?vimeo\.com/|player\.vimeo\.com/)'
  ),
  constraint community_fly_patterns_cover_path check (
    cover_image_path is null
    or cover_image_path like owner_id::text || '/' || id::text || '/%'
  )
);

-- Materials and steps are normalized so ordering can be changed without storing
-- an opaque JSON recipe. A step may reference one private-bucket image.
create table if not exists public.community_fly_pattern_materials (
  id bigint generated by default as identity primary key,
  pattern_id uuid not null references public.community_fly_patterns(id) on delete cascade,
  position integer not null check (position > 0),
  name text not null check (length(btrim(name)) between 1 and 160),
  quantity text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (pattern_id, position)
);

create table if not exists public.community_fly_pattern_steps (
  id uuid primary key default gen_random_uuid(),
  pattern_id uuid not null references public.community_fly_patterns(id) on delete cascade,
  position integer not null check (position > 0),
  instruction text not null check (length(btrim(instruction)) > 0),
  image_path text,
  image_alt_text text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (pattern_id, position)
);

-- Audit rows survive pattern deletion. pattern_id becomes null, while
-- pattern_id_snapshot and pattern_snapshot retain what was acted upon.
create table if not exists public.community_fly_pattern_moderation_log (
  id bigint generated by default as identity primary key,
  pattern_id uuid references public.community_fly_patterns(id) on delete set null,
  pattern_id_snapshot uuid not null,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null check (
    action in ('submitted', 'published', 'rejected', 'moderator_edited', 'deleted')
  ),
  from_status text,
  to_status text,
  reason text,
  details jsonb not null default '{}'::jsonb,
  pattern_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists community_fly_patterns_public_idx
  on public.community_fly_patterns (published_at desc, created_at desc)
  where status = 'published';
create index if not exists community_fly_patterns_owner_idx
  on public.community_fly_patterns (owner_id, updated_at desc);
create index if not exists community_fly_patterns_queue_idx
  on public.community_fly_patterns (status, submitted_at asc);
create index if not exists community_fly_materials_pattern_idx
  on public.community_fly_pattern_materials (pattern_id, position);
create index if not exists community_fly_steps_pattern_idx
  on public.community_fly_pattern_steps (pattern_id, position);
create index if not exists community_fly_audit_pattern_idx
  on public.community_fly_pattern_moderation_log (pattern_id_snapshot, created_at desc);

-- Fixed-search-path SECURITY DEFINER helpers prevent callers from substituting
-- objects through search_path. They expose authorization decisions, not roles.
create or replace function public.can_read_community_fly_pattern(
  check_pattern_id uuid,
  check_user_id uuid default auth.uid()
) returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.community_fly_patterns p
    where p.id = check_pattern_id
      and (
        p.status = 'published'
        or (check_user_id is not null and p.owner_id = check_user_id)
        or (check_user_id is not null and public.is_moderator(check_user_id))
      )
  );
$$;

create or replace function public.can_edit_community_fly_pattern(
  check_pattern_id uuid,
  check_user_id uuid default auth.uid()
) returns boolean
language sql stable security definer set search_path = ''
as $$
  select check_user_id is not null and exists (
    select 1 from public.community_fly_patterns p
    where p.id = check_pattern_id
      and (
        (p.owner_id = check_user_id and p.status in ('draft', 'rejected'))
        or public.is_moderator(check_user_id)
      )
  );
$$;

