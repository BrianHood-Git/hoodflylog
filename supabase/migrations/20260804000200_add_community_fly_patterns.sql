-- updated_at maintenance. Child edits also touch the parent so list views and
-- caches see recipe changes.
create or replace function public.touch_community_fly_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.touch_community_fly_parent()
returns trigger language plpgsql security definer set search_path = '' as $$
declare target_id uuid;
begin
  target_id := case when tg_op = 'DELETE' then old.pattern_id else new.pattern_id end;
  update public.community_fly_patterns set updated_at = now() where id = target_id;
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

-- Non-moderators cannot forge ownership, moderation fields, or status changes.
-- Submission is performed by the audited RPC below.
create or replace function public.protect_community_fly_pattern_write()
returns trigger language plpgsql security definer set search_path = '' as $$
declare caller uuid := auth.uid();
declare moderator boolean := caller is not null and public.is_moderator(caller);
begin
  if caller is null then raise exception 'Authentication required'; end if;

  if tg_op = 'INSERT' then
    if not moderator then
      new.owner_id := caller;
      new.status := 'draft';
      new.rejection_reason := null;
      new.submitted_at := null;
      new.published_at := null;
      new.moderated_at := null;
      new.moderated_by := null;
      if public.is_banned(caller) then raise exception 'Banned users cannot create patterns'; end if;
    elsif new.owner_id is null then
      new.owner_id := caller;
    end if;
  else
    new.owner_id := old.owner_id;
    new.created_at := old.created_at;
    if not moderator then
      if old.owner_id <> caller or old.status not in ('draft', 'rejected') then
        raise exception 'Only editable drafts owned by the caller may be changed';
      end if;
      if coalesce(current_setting('hoodflylog.fly_workflow', true), '') <> 'submit'
         and new.status is distinct from old.status then
        raise exception 'Use submit_community_fly_pattern() to change status';
      end if;
      if coalesce(current_setting('hoodflylog.fly_workflow', true), '') <> 'submit' then
        new.rejection_reason := old.rejection_reason;
        new.submitted_at := old.submitted_at;
        new.published_at := old.published_at;
        new.moderated_at := old.moderated_at;
        new.moderated_by := old.moderated_by;
      end if;
    end if;
  end if;
  return new;
end;
$$;

-- Step paths must belong to the same owner/pattern directory as their parent.
create or replace function public.validate_community_fly_step_image_path()
returns trigger language plpgsql security definer set search_path = '' as $$
declare expected_prefix text;
begin
  if new.image_path is null then return new; end if;
  select p.owner_id::text || '/' || p.id::text || '/steps/' into expected_prefix
  from public.community_fly_patterns p where p.id = new.pattern_id;
  if expected_prefix is null or new.image_path not like expected_prefix || '%' then
    raise exception 'Step image path must be inside the pattern steps directory';
  end if;
  return new;
end;
$$;

-- Deletions are always logged, including an owner's draft deletion.
create or replace function public.audit_community_fly_pattern_delete()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if coalesce(current_setting('hoodflylog.skip_fly_delete_audit', true), '') <> 'on' then
    insert into public.community_fly_pattern_moderation_log
      (pattern_id, pattern_id_snapshot, actor_id, action, from_status, pattern_snapshot)
    values (old.id, old.id, auth.uid(), 'deleted', old.status, to_jsonb(old));
  end if;
  return old;
end;
$$;

