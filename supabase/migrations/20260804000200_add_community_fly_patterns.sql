-- Audited workflow RPC: owners submit complete draft/rejected recipes.
create or replace function public.submit_community_fly_pattern(target_pattern_id uuid)
returns public.community_fly_patterns
language plpgsql security definer set search_path = '' as $$
declare caller uuid := auth.uid();
declare previous public.community_fly_patterns;
declare result public.community_fly_patterns;
begin
  if caller is null then raise exception 'Authentication required'; end if;
  if public.is_banned(caller) then raise exception 'Banned users cannot submit patterns'; end if;
  select * into previous from public.community_fly_patterns
    where id = target_pattern_id for update;
  if previous.id is null or previous.owner_id <> caller then raise exception 'Pattern not found'; end if;
  if previous.status not in ('draft', 'rejected') then raise exception 'Pattern is not submit-ready'; end if;
  if not exists (select 1 from public.community_fly_pattern_materials where pattern_id = target_pattern_id)
     or not exists (select 1 from public.community_fly_pattern_steps where pattern_id = target_pattern_id) then
    raise exception 'At least one material and one tying step are required';
  end if;
  perform set_config('hoodflylog.fly_workflow', 'submit', true);
  update public.community_fly_patterns set
    status = 'pending', submitted_at = now(), published_at = null,
    rejection_reason = null, moderated_at = null, moderated_by = null
    where id = target_pattern_id returning * into result;
  insert into public.community_fly_pattern_moderation_log
    (pattern_id, pattern_id_snapshot, actor_id, action, from_status, to_status, pattern_snapshot)
  values (result.id, result.id, caller, 'submitted', previous.status, result.status, to_jsonb(result));
  return result;
end;
$$;

-- Moderation decisions are centralized so status and audit data cannot diverge.
create or replace function public.moderate_community_fly_pattern(
  target_pattern_id uuid, decision text, moderation_reason text default null
) returns public.community_fly_patterns
language plpgsql security definer set search_path = '' as $$
declare caller uuid := auth.uid();
declare previous public.community_fly_patterns;
declare result public.community_fly_patterns;
begin
  if caller is null or not public.is_moderator(caller) then raise exception 'Moderator access required'; end if;
  if decision not in ('published', 'rejected') then raise exception 'Decision must be published or rejected'; end if;
  if decision = 'rejected' and nullif(btrim(moderation_reason), '') is null then
    raise exception 'A rejection reason is required';
  end if;
  select * into previous from public.community_fly_patterns where id = target_pattern_id for update;
  if previous.id is null then raise exception 'Pattern not found'; end if;
  if previous.status = 'draft' then raise exception 'The owner must submit this draft first'; end if;
  update public.community_fly_patterns set
    status = decision,
    rejection_reason = case when decision = 'rejected' then moderation_reason else null end,
    published_at = case when decision = 'published' then coalesce(published_at, now()) else null end,
    moderated_at = now(), moderated_by = caller
    where id = target_pattern_id returning * into result;
  insert into public.community_fly_pattern_moderation_log
    (pattern_id, pattern_id_snapshot, actor_id, action, from_status, to_status, reason, pattern_snapshot)
  values (result.id, result.id, caller, decision, previous.status, result.status,
          moderation_reason, to_jsonb(result));
  return result;
end;
$$;

-- Moderators edit parent metadata through a whitelist rather than receiving a
-- blanket UPDATE policy that could silently bypass moderation auditing.
create or replace function public.moderator_update_community_fly_pattern(
  target_pattern_id uuid, changes jsonb
) returns public.community_fly_patterns
language plpgsql security definer set search_path = '' as $$
declare caller uuid := auth.uid();
declare result public.community_fly_patterns;
begin
  if caller is null or not public.is_moderator(caller) then raise exception 'Moderator access required'; end if;
  update public.community_fly_patterns set
    name = case when changes ? 'name' then btrim(changes->>'name') else name end,
    category = case when changes ? 'category' then btrim(changes->>'category') else category end,
    summary = case when changes ? 'summary' then nullif(changes->>'summary', '') else summary end,
    best_for = case when changes ? 'best_for' then nullif(changes->>'best_for', '') else best_for end,
    fishing_notes = case when changes ? 'fishing_notes' then nullif(changes->>'fishing_notes', '') else fishing_notes end,
    video_url = case when changes ? 'video_url' then nullif(changes->>'video_url', '') else video_url end,
    cover_image_path = case when changes ? 'cover_image_path' then nullif(changes->>'cover_image_path', '') else cover_image_path end
    where id = target_pattern_id returning * into result;
  if result.id is null then raise exception 'Pattern not found'; end if;
  insert into public.community_fly_pattern_moderation_log
    (pattern_id, pattern_id_snapshot, actor_id, action, from_status, to_status, details, pattern_snapshot)
  values (result.id, result.id, caller, 'moderator_edited', result.status, result.status,
          jsonb_build_object('changed_keys', (select jsonb_agg(key) from jsonb_object_keys(changes) key)),
          to_jsonb(result));
  return result;
end;
$$;

create or replace function public.moderator_delete_community_fly_pattern(
  target_pattern_id uuid, deletion_reason text default null
) returns void
language plpgsql security definer set search_path = '' as $$
declare caller uuid := auth.uid();
declare target public.community_fly_patterns;
begin
  if caller is null or not public.is_moderator(caller) then raise exception 'Moderator access required'; end if;
  select * into target from public.community_fly_patterns where id = target_pattern_id for update;
  if target.id is null then raise exception 'Pattern not found'; end if;
  insert into public.community_fly_pattern_moderation_log
    (pattern_id, pattern_id_snapshot, actor_id, action, from_status, reason, pattern_snapshot)
  values (target.id, target.id, caller, 'deleted', target.status, deletion_reason, to_jsonb(target));
  perform set_config('hoodflylog.skip_fly_delete_audit', 'on', true);
  delete from public.community_fly_patterns where id = target_pattern_id;
end;
$$;

